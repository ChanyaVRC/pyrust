#[cfg(test)]
mod tests {
    use super::*;

    /// `in_ranges` relies on each table being sorted ascending and
    /// non-overlapping. Guard that invariant so a bad regeneration is caught.
    fn assert_sorted_disjoint(ranges: &[(u32, u32)]) {
        for w in ranges.windows(2) {
            assert!(w[0].0 <= w[0].1, "range {:?} is inverted", w[0]);
            assert!(
                w[0].1 < w[1].0,
                "ranges {:?} and {:?} overlap or are unsorted",
                w[0],
                w[1]
            );
        }
        if let Some(last) = ranges.last() {
            assert!(last.0 <= last.1, "range {last:?} is inverted");
        }
    }

    #[test]
    fn range_tables_are_sorted_and_disjoint() {
        assert_sorted_disjoint(XID_START_RANGES);
        assert_sorted_disjoint(XID_CONTINUE_RANGES);
        assert_sorted_disjoint(NUMERIC_RANGES);
    }

    #[test]
    fn spot_checks_match_cpython_3_12() {
        // isidentifier building blocks
        assert!(is_xid_start('_'));
        assert!(is_xid_start('π'));
        assert!(!is_xid_start('1'));
        assert!(is_xid_continue('1'));
        assert!(is_xid_continue('\u{301}')); // combining acute: continue, not start
        assert!(!is_xid_start('\u{301}'));
        assert!(!is_xid_continue('\u{b2}')); // superscript two: not an identifier char

        // isnumeric: CJK ideographic numerals and roman numerals
        assert!(is_numeric('一'));
        assert!(is_numeric('\u{2167}')); // Ⅷ
        assert!(!is_numeric('A'));

        // titlecase: Lt digraph and SpecialCasing
        assert_eq!(to_titlecase('ǆ'), Some("ǅ"));
        assert_eq!(to_titlecase('ß'), Some("Ss"));
        assert_eq!(to_titlecase('A'), None); // falls back to to_uppercase

        // casefold exceptions
        assert_eq!(casefold_exception('µ'), Some("μ"));
        assert_eq!(casefold_exception('ς'), Some("σ"));
        assert_eq!(casefold_exception('a'), None);
    }
}
