def show(func, *args, **kwargs):
    try:
        result = func(*args, **kwargs)
    except Exception as exc:
        print(func.__name__, "->", type(exc).__name__ + ":", exc)
    else:
        print(func.__name__, "->", type(result).__name__, repr(result))


